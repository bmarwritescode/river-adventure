"""Map origin and play-area boundary.

Origin: the OSM node shared by E 45th St and Duval St, pinned in src/world/mapOrigin.json
(shared with the game). Pinned so small OSM edits never shift every clue location.

Boundary: derived once from the boundary streets' centerlines, then saved to
tools/map/boundary.geojson, which is the editable source of truth from then on.
"""

from __future__ import annotations

import json
import math
from dataclasses import dataclass, field

from shapely.geometry import LineString, MultiLineString, Point, Polygon
from shapely.ops import polygonize, unary_union

import config
from osm_parse import OsmData
from projection import Origin, Projector


# --- Origin ------------------------------------------------------------------------------------

def find_origin_node(osm: OsmData) -> tuple[int, float, float]:
    a, b = config.ORIGIN_STREETS
    common = osm.street_nodes(a) & osm.street_nodes(b)
    if not common:
        raise RuntimeError(f"No OSM node shared by {a!r} and {b!r}")
    if len(common) > 1:
        print(f"[origin] warning: {len(common)} shared nodes, using the lowest id")
    nid = min(common)
    lat, lon = osm.nodes_ll[nid]
    return nid, lat, lon


def load_or_create_origin(osm: OsmData, regen: bool) -> Origin:
    nid, lat, lon = find_origin_node(osm)
    if config.ORIGIN_FILE.exists() and not regen:
        pinned = json.loads(config.ORIGIN_FILE.read_text())
        origin = Origin(pinned["lat"], pinned["lon"])
        drift = Projector(origin).to_world(lat, lon)
        d = math.hypot(*drift)
        print(f"[origin] pinned {origin.lat:.7f}, {origin.lon:.7f} (OSM node now {d:.2f} m away)")
        if d > 0.5:
            print("[origin]   OSM node moved; keeping the pinned origin (use --regen-origin to re-pin).")
        return origin
    origin = Origin(lat, lon)
    e, n = origin.utm
    payload = {
        "_comment": "Map origin = E 45th St & Duval St. Generated by tools/map (--regen-origin). "
        "World: x = easting - utmEasting, z = -(northing - utmNorthing). Changing this moves every world coordinate.",
        "osmNodeId": nid,
        "lat": lat,
        "lon": lon,
        "epsg": 32614,
        "utmEasting": round(e, 3),
        "utmNorthing": round(n, 3),
    }
    config.ORIGIN_FILE.write_text(json.dumps(payload, indent=2) + "\n")
    print(f"[origin] pinned new origin node {nid} at {lat:.7f}, {lon:.7f} -> {config.ORIGIN_FILE}")
    return origin


# --- Boundary ------------------------------------------------------------------------------------

def _parts(geom) -> list[LineString]:
    if geom is None or geom.is_empty:
        return []
    if isinstance(geom, LineString):
        return [geom]
    if isinstance(geom, MultiLineString):
        return list(geom.geoms)
    return [g for g in getattr(geom, "geoms", []) if isinstance(g, LineString)]


def _end_rays(line: LineString, length: float):
    """Yield (endpoint, ray LineString extending outward from that end)."""
    c = list(line.coords)
    for end, prev in ((c[0], c[1]), (c[-1], c[-2])):
        dx, dz = end[0] - prev[0], end[1] - prev[1]
        n = math.hypot(dx, dz) or 1.0
        far = (end[0] + dx / n * length, end[1] + dz / n * length)
        yield Point(end), LineString([end, far])


@dataclass
class Boundary:
    polygon: Polygon  # world XZ
    decisions: list[str]
    # Synthetic boundary stretches not backed by a real street (extensions / gap bridges), world XZ.
    connectors: list[LineString] = field(default_factory=list)


def _describe_ground_truth(osm: OsmData, seg: LineString) -> str:
    """Say which named road (if any) actually runs along a synthetic connector."""
    corridor = seg.buffer(25)
    overlap: dict[str, float] = {}
    for w in osm.ways.values():
        name = w.tags.get("name")
        if name and w.tags.get("highway") not in (None, "footway", "path", "service", "cycleway") and len(w.coords) >= 2:
            ln = LineString(w.coords).intersection(corridor).length
            if ln > 0:
                overlap[name] = overlap.get(name, 0.0) + ln
    best = max(overlap.items(), key=lambda kv: kv[1], default=None)
    if best and best[1] > 0.5 * seg.length:
        return f"It runs along {best[0]} (within 25 m)."
    return "No named road runs there in OSM, so it cuts straight across."


def derive_boundary(osm: OsmData) -> Boundary:
    """Derive the boundary polygon (world XZ) from the boundary streets' centerlines."""
    notes: list[str] = []
    sides: dict[str, list[LineString]] = {}
    for side, names in config.BOUNDARY_STREETS.items():
        parts = _parts(osm.street_lines(names))
        if not parts:
            raise RuntimeError(f"No OSM ways found for {side} boundary streets {names}")
        sides[side] = parts
    if config.CLOSE_SOUTHEAST_ALONG_I35:
        sides["i35"] = _parts(osm.street_lines([], ref=config.I35_REF, highway={"motorway"}))
        notes.append("South-east corner closed along I-35 (southbound main lanes), because Airport Blvd "
                     "crosses I-35 near 45th St and 38th St is broken at the interstate.")
    else:
        notes.append("South-east corner follows 38th St across I-35 to Airport Blvd (literal reading).")

    ext = config.BOUNDARY_END_EXTENSION_M
    extra: list[tuple[LineString, str]] = []  # (connector segment, description)
    for side, parts in sides.items():
        if side == "i35":
            continue
        others = unary_union([p for s, ps in sides.items() if s != side for p in ps])
        own_all = unary_union(parts)
        for i, line in enumerate(parts):
            own_others = unary_union([p for j, p in enumerate(parts) if j != i]) if len(parts) > 1 else None
            for end, ray in _end_rays(line, ext):
                if end.distance(others) < 0.5 or (own_others is not None and end.distance(own_others) < 0.5):
                    continue  # already connected
                hit = ray.intersection(others)
                if not hit.is_empty:
                    # Extend straight to the nearest crossing with a neighbouring boundary street.
                    pts = [g for g in getattr(hit, "geoms", [hit])]
                    nearest = min(pts, key=lambda g: end.distance(g))
                    p = nearest if isinstance(nearest, Point) else nearest.interpolate(nearest.project(end))
                    d = end.distance(p)
                    if d > 1.0:
                        dx, dz = (p.x - end.x) / d, (p.y - end.y) / d
                        extra.append((LineString([(end.x, end.y), (p.x + dx * 2, p.y + dz * 2)]),
                                      f"{' / '.join(config.BOUNDARY_STREETS[side])} extended {d:.0f} m in a "
                                      f"straight line to meet the next boundary street (it stops short in OSM)."))
                elif own_others is not None and not own_others.is_empty:
                    # Bridge a gap in the same street (e.g. 38th St broken at I-35).
                    q = own_others.interpolate(own_others.project(end))
                    d = end.distance(q)
                    if 1.0 < d < ext and q.distance(own_all) < 0.01:
                        extra.append((LineString([(end.x, end.y), (q.x, q.y)]),
                                      f"Bridged a {d:.0f} m gap in {' / '.join(config.BOUNDARY_STREETS[side])}."))

    network = unary_union([p for ps in sides.values() for p in ps] + [seg for seg, _ in extra])
    faces = list(polygonize(network))
    origin = Point(0, 0)
    containing = [f for f in faces if f.contains(origin)]
    if not containing:
        raise RuntimeError("Boundary streets don't enclose the origin; adjust config.BOUNDARY_STREETS")
    poly = min(containing, key=lambda f: f.area)
    # Only report connectors that actually ended up on the final boundary.
    used: list[LineString] = []
    for seg, desc in extra:
        on_boundary = poly.exterior.intersection(seg.buffer(0.05))
        if on_boundary.length > 1.0:
            notes.append(f"{desc} {_describe_ground_truth(osm, seg)}")
            used.append(seg)
    poly = Polygon(poly.exterior).simplify(config.BOUNDARY_SIMPLIFY_M, preserve_topology=True)
    return Boundary(poly, notes, used)


def _ll(proj: Projector, coords) -> list[list[float]]:
    out = []
    for x, z in coords:
        lat, lon = proj.to_latlon(x, z)
        out.append([round(lon, 7), round(lat, 7)])  # ~1 cm
    return out


def save_boundary(b: Boundary, proj: Projector) -> None:
    features = [{
        "type": "Feature",
        "properties": {
            "name": "Play area boundary",
            "note": "Edit freely (e.g. paste this file into geojson.io). Coordinates are [lon, lat]. "
            "Re-derive from the streets with: npm run map:build -- --regen-boundary",
            "decisions": b.decisions,
        },
        "geometry": {"type": "Polygon", "coordinates": [_ll(proj, b.polygon.exterior.coords)]},
    }]
    for seg in b.connectors:
        features.append({
            "type": "Feature",
            "properties": {"role": "connector", "note": "Synthetic stretch (no real street here); informational only."},
            "geometry": {"type": "LineString", "coordinates": _ll(proj, seg.coords)},
        })
    config.BOUNDARY_FILE.write_text(json.dumps({"type": "FeatureCollection", "features": features}, indent=1) + "\n")
    print(f"[boundary] wrote {config.BOUNDARY_FILE} ({len(b.polygon.exterior.coords)} points)")


def load_boundary(proj: Projector) -> Boundary:
    data = json.loads(config.BOUNDARY_FILE.read_text())
    poly = None
    decisions: list[str] = []
    connectors: list[LineString] = []
    for feat in data["features"]:
        g = feat["geometry"]
        if g["type"] == "Polygon" and poly is None:
            poly = Polygon([proj.to_world(lat, lon) for lon, lat in g["coordinates"][0]])
            decisions = feat.get("properties", {}).get("decisions", [])
        elif g["type"] == "LineString":
            connectors.append(LineString([proj.to_world(lat, lon) for lon, lat in g["coordinates"]]))
    if poly is None:
        raise RuntimeError(f"{config.BOUNDARY_FILE} has no Polygon feature")
    if not poly.is_valid:
        raise RuntimeError(f"{config.BOUNDARY_FILE} is not a valid polygon (self-intersecting?)")
    return Boundary(poly, decisions, connectors)


def load_or_create_boundary(osm: OsmData, proj: Projector, regen: bool) -> Boundary:
    if config.BOUNDARY_FILE.exists() and not regen:
        print(f"[boundary] using {config.BOUNDARY_FILE.name} (edit it, or --regen-boundary to re-derive)")
        return load_boundary(proj)
    save_boundary(derive_boundary(osm), proj)
    return load_boundary(proj)  # round-trip so the pipeline always uses exactly what's in the file
